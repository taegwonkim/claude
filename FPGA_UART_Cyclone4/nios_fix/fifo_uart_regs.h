/*
 * fifo_uart_regs.h
 *   rtl/fifo_uart_avalon.v (Platform Designer 컴포넌트 "FIFO UART") 레지스터 정의
 */
#ifndef FIFO_UART_REGS_H_
#define FIFO_UART_REGS_H_

#include <io.h>

#define FIFO_UART_DATA_REG				0
#define FIFO_UART_STATUS_REG			1
#define FIFO_UART_CONTROL_REG			2
#define FIFO_UART_TXCOUNT_REG			3

#define IORD_FIFO_UART_DATA(base)		IORD(base, FIFO_UART_DATA_REG)
#define IOWR_FIFO_UART_DATA(base, d)	IOWR(base, FIFO_UART_DATA_REG, d)
#define IORD_FIFO_UART_STATUS(base)		IORD(base, FIFO_UART_STATUS_REG)
#define IOWR_FIFO_UART_STATUS(base, d)	IOWR(base, FIFO_UART_STATUS_REG, d)
#define IORD_FIFO_UART_CONTROL(base)	IORD(base, FIFO_UART_CONTROL_REG)
#define IOWR_FIFO_UART_CONTROL(base, d)	IOWR(base, FIFO_UART_CONTROL_REG, d)
#define IORD_FIFO_UART_TXCOUNT(base)	IORD(base, FIFO_UART_TXCOUNT_REG)

/* DATA */
#define FIFO_UART_DATA_MSK				(0x000000FF)
#define FIFO_UART_DATA_VALID_MSK		(0x00000100)

/* STATUS */
#define FIFO_UART_STATUS_RX_AVAIL_MSK	(0x00000001)
#define FIFO_UART_STATUS_TX_FULL_MSK	(0x00000002)
#define FIFO_UART_STATUS_TX_IDLE_MSK	(0x00000004)
#define FIFO_UART_STATUS_RX_OVF_MSK		(0x00000008)
#define FIFO_UART_STATUS_RX_FERR_MSK	(0x00000010)
#define FIFO_UART_STATUS_RX_COUNT_OFST	(16)

/* CONTROL */
#define FIFO_UART_CONTROL_RXIE_MSK		(0x00000001)

#endif /* FIFO_UART_REGS_H_ */
