/**
 * @brief Malloc Failed Hook - called when pvPortMalloc() fails
 */
void vApplicationMallocFailedHook(void)
{
    /* Blink fault LED rapidly to indicate memory issue */
    for (;;) {
        HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_1);
        HAL_Delay(100);
    }
}

/**
 * @brief Stack Overflow Hook - called when stack overflow is detected
 */
void vApplicationStackOverflowHook(TaskHandle_t xTask, char *pcTaskName)
{
    (void)xTask;
    (void)pcTaskName;
    /* Blink both LEDs to indicate stack overflow */
    for (;;) {
        HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_1);
        HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
        HAL_Delay(200);
    }
}
