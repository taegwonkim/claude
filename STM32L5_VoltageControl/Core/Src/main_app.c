/**
 ******************************************************************************
 * @file    main_app.c
 * @brief   Main Application - FreeRTOS Task Implementations
 ******************************************************************************
 *
 * 시스템 구조:
 *
 *  [PC UART] ←→ [UartCmdTask] → [UartCmdQueue] → [VoltageCtrlTask]
 *                                                        ↓
 *  [MCP3465R] ← [AdcReadTask] → [AdcDataQueue] → [VoltageCtrlTask]
 *       ↑ SPI                           ↓              ↓ DAC/PWM
 *                              [CommTxQueue] → [CommTxTask] → [UART + FDCAN]
 *
 *  [Internal ADC] → [FaultDetectTask] → [FaultEventQueue] → [CommTxTask]
 *                          ↓
 *                   채널 차단 (단락 시)
 *
 ******************************************************************************
 */
